def p(text):
    return doc.add_paragraph(text)


def heading(text):
    doc.add_heading(text, 1)


def page(text):
    doc.add_page_break(); heading(text)


def table(headers, rows, widths):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for column, width in zip(t.columns, widths):
        column.width = Cm(width)
    for cell, text in zip(t.rows[0].cells,headers): cell.text=text
    for row in rows:
        for cell,text in zip(t.add_row().cells,row): cell.text=str(text)
    for ri,row in enumerate(t.rows):
        for ci,cell in enumerate(row.cells):
            cell.width=Cm(widths[ci]); cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            props=cell._tc.get_or_add_tcPr()
            borders=OxmlElement("w:tcBorders")
            for edge in ("top","left","bottom","right"):
                item=OxmlElement("w:"+edge); item.set(qn("w:val"),"single"); item.set(qn("w:sz"),"4"); item.set(qn("w:color"),"D9D9D9"); borders.append(item)
            props.append(borders)
            margins=OxmlElement("w:tcMar")
            for edge in ("top","left","bottom","right"):
                item=OxmlElement("w:"+edge); item.set(qn("w:w"),"90"); item.set(qn("w:type"),"dxa"); margins.append(item)
            props.append(margins)
            if ri==0:
                shade=OxmlElement("w:shd"); shade.set(qn("w:fill"),"DCE6F1"); props.append(shade)
            for para in cell.paragraphs:
                para.paragraph_format.space_after=Pt(3); para.paragraph_format.line_spacing=1.05
                for run in para.runs:
                    run.font.size=Pt(9); run.bold=ri==0
        rowpr=row._tr.get_or_add_trPr(); rowpr.append(OxmlElement("w:cantSplit"))
    t.rows[0]._tr.get_or_add_trPr().append(OxmlElement("w:tblHeader"))
    p("")
    return t


